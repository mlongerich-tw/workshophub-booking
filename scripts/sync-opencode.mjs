#!/usr/bin/env node
// Keep OpenCode in lockstep with the Claude Code setup. Claude is the single source of truth.
//
//   Source (edit these)                    Generated / wired for OpenCode
//   CLAUDE.md                          →   read natively by OpenCode (no AGENTS.md on purpose);
//                                          its @imports become opencode.json "instructions"
//   .claude/skills/<name>/SKILL.md     →   read natively by OpenCode as skills, plus
//                                          .opencode/commands/<name>.md so /<name> works
//   .claude/agents/<name>.md           →   .opencode/agents/<name>.md (tools → permissions)
//   .claude/hooks/<agent>-allowlist.txt→   native read/edit path permissions for that agent
//   .claude/settings.json hooks        →   run live by .opencode/plugins/claude-hooks-bridge.ts
//
// Usage:
//   node scripts/sync-opencode.mjs          regenerate (make sync-opencode)
//   node scripts/sync-opencode.mjs --check  exit 1 on drift (make check-opencode, pre-push, CI)
//   node scripts/sync-opencode.mjs --hook   PostToolUse hook: regenerate when a source changed
//
// No dependencies; output is deterministic so --check is a byte comparison.

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync } from 'node:fs'
import { join, dirname, relative, isAbsolute, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const MARKER = 'GENERATED by scripts/sync-opencode.mjs'

const TOOL_NOTE = [
  '> **OpenCode note (generated):** this prompt is shared with Claude Code. Tool names map as',
  '> Read→`read`, Write→`write`, Edit→`edit`, Grep→`grep`, Glob→`glob`, Bash→`shell`,',
  '> AskUserQuestion→`question`, Agent→`subagent`, Skill→`skill`. Project rules, `make` targets and',
  '> hooks are identical in both tools.',
].join('\n')

// Claude tool name(s) → OpenCode permission action.
const ACTIONS = {
  read: ['Read'],
  grep: ['Grep'],
  glob: ['Glob'],
  edit: ['Write', 'Edit', 'MultiEdit', 'NotebookEdit'],
  shell: ['Bash'],
  webfetch: ['WebFetch'],
  websearch: ['WebSearch'],
  subagent: ['Agent', 'Task'],
  skill: ['Skill'],
}

const rel = (p) => relative(ROOT, p).split('\\').join('/')
const read = (p) => readFileSync(p, 'utf8')
const q = (s) => JSON.stringify(s) // JSON string == valid YAML double-quoted scalar

/** Minimal frontmatter parser: top-level `key: value` lines only (all our sources). */
function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)
  if (!m) return { data: {}, body: text }
  const data = {}
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/)
    if (!kv) continue
    let v = kv[2].trim()
    if (/^(['"]).*\1$/.test(v)) v = v.slice(1, -1)
    data[kv[1]] = v
  }
  return { data, body: m[2] }
}

function header(source) {
  return `# ${MARKER} from ${source}. Do not edit; edit the source and run \`make sync-opencode\`.`
}

function readAllowlist(agent) {
  const file = join(ROOT, '.claude', 'hooks', `${agent}-allowlist.txt`)
  if (!existsSync(file)) return null
  const out = { read: [], write: [] }
  for (const line of read(file).split('\n')) {
    const m = line.match(/^(read|write)\s+(\S+)/)
    if (m) out[m[1]].push(m[2])
  }
  return { ...out, source: rel(file) }
}

const isDir = (p) => {
  try {
    return readdirSync(join(ROOT, p)) !== undefined
  } catch {
    return false
  }
}

function agentFile(srcPath) {
  const name = srcPath.split('/').pop().replace(/\.md$/, '')
  const { data, body } = parseFrontmatter(read(srcPath))
  const tools = data.tools ? data.tools.split(',').map((t) => t.trim()) : null
  const perms = []
  const rule = (action, resource, effect) => perms.push({ action, resource, effect })

  if (tools) {
    for (const [action, claudeTools] of Object.entries(ACTIONS)) {
      if (!claudeTools.some((t) => tools.includes(t))) rule(action, '*', 'deny')
    }
  }

  const allow = readAllowlist(name)
  if (allow) {
    // Native path rules (last match wins): deny everything, then allow the list.
    // grep/glob resources are search patterns, not paths, so those stay with the
    // bridge-run guard hook, which checks their resolved paths.
    rule('read', '*', 'deny')
    for (const p of allow.read) {
      rule('read', p, 'allow')
      if (isDir(p)) rule('read', `${p}/**`, 'allow')
    }
    rule('edit', '*', 'deny')
    for (const p of allow.write) rule('edit', isDir(p) ? `${p}/**` : p, 'allow')
  }

  const sources = [rel(srcPath), allow?.source].filter(Boolean).join(' + ')
  const lines = ['---', header(sources), `description: ${q(data.description ?? name)}`, 'mode: subagent']
  if (data.model && data.model !== 'inherit') lines.push(`# Claude model "${data.model}" not mapped; OpenCode inherits the parent model.`)
  if (perms.length) {
    lines.push('permissions:')
    for (const p of perms) {
      lines.push(`  - action: ${p.action}`, `    resource: ${q(p.resource)}`, `    effect: ${p.effect}`)
    }
  }
  lines.push('---', '', TOOL_NOTE, '', body.trim(), '')
  return { path: join(ROOT, '.opencode', 'agents', `${name}.md`), content: lines.join('\n') }
}

function commandFile(skillDir) {
  const name = skillDir.split('/').pop()
  const src = join(skillDir, 'SKILL.md')
  const { data, body } = parseFrontmatter(read(src))
  const lines = [
    '---',
    header(rel(src)),
    `description: ${q(data.description ?? name)}`,
    '---',
    '',
    TOOL_NOTE,
    '',
    body.trim(),
    '',
  ]
  return { path: join(ROOT, '.opencode', 'commands', `${name}.md`), content: lines.join('\n') }
}

function opencodeJson() {
  const path = join(ROOT, 'opencode.json')
  const current = existsSync(path) ? JSON.parse(read(path)) : { $schema: 'https://opencode.ai/config.json' }
  const imports = read(join(ROOT, 'CLAUDE.md'))
    .split('\n')
    .map((l) => l.match(/^@(\S+)\s*$/)?.[1])
    .filter(Boolean)
  const next = { ...current, instructions: imports }
  return { path, content: JSON.stringify(next, null, 2) + '\n' }
}

function listDir(dir, filter) {
  const abs = join(ROOT, dir)
  if (!existsSync(abs)) return []
  return readdirSync(abs, { withFileTypes: true }).filter(filter).map((d) => join(abs, d.name))
}

function plan() {
  const files = [
    ...listDir('.claude/agents', (d) => d.isFile() && d.name.endsWith('.md')).map(agentFile),
    ...listDir('.claude/skills', (d) => d.isDirectory())
      .filter((d) => existsSync(join(d, 'SKILL.md')))
      .map(commandFile),
    opencodeJson(),
  ]
  const wanted = new Set(files.map((f) => f.path))
  const orphans = ['.opencode/agents', '.opencode/commands']
    .flatMap((d) => listDir(d, (e) => e.isFile() && e.name.endsWith('.md')))
    .filter((p) => !wanted.has(p) && read(p).includes(MARKER))
  return { files, orphans }
}

function drift({ files, orphans }) {
  const changed = files.filter((f) => !existsSync(f.path) || read(f.path) !== f.content)
  return { changed, orphans }
}

function sync() {
  const p = plan()
  const { changed, orphans } = drift(p)
  for (const f of changed) {
    mkdirSync(dirname(f.path), { recursive: true })
    writeFileSync(f.path, f.content)
  }
  for (const o of orphans) rmSync(o)
  return { changed: changed.map((f) => rel(f.path)), removed: orphans.map(rel) }
}

const SOURCE_RE = /^(CLAUDE\.md|\.claude\/agents\/[^/]+\.md|\.claude\/skills\/[^/]+\/SKILL\.md|\.claude\/hooks\/[^/]+-allowlist\.txt)$/
const GENERATED_RE = /^(\.opencode\/(agents|commands)\/[^/]+\.md|opencode\.json)$/

function hookMode() {
  let payload = {}
  try {
    payload = JSON.parse(readFileSync(0, 'utf8') || '{}')
  } catch {
    return 0
  }
  const raw = payload?.tool_input?.file_path ?? payload?.tool_response?.filePath
  if (typeof raw !== 'string') return 0
  const file = rel(isAbsolute(raw) ? raw : join(ROOT, raw))
  if (SOURCE_RE.test(file)) {
    const { changed, removed } = sync()
    if (changed.length || removed.length) {
      console.log(`OpenCode parity: regenerated ${[...changed, ...removed].join(', ')}`)
    }
    return 0
  }
  if (GENERATED_RE.test(file)) {
    const { changed } = sync()
    if (changed.includes(file)) {
      console.error(
        `${file} is generated from the Claude setup and your edit was reverted. ` +
          'Edit the source instead (CLAUDE.md, .claude/agents, .claude/skills, .claude/hooks/*-allowlist.txt), ' +
          'or for opencode.json edit keys other than "instructions".'
      )
      return 2
    }
  }
  return 0
}

function main() {
  const mode = process.argv[2]
  if (mode === '--hook') process.exit(hookMode())
  if (mode === '--check') {
    const { changed, orphans } = drift(plan())
    if (changed.length || orphans.length) {
      console.error('OpenCode parity drift detected (Claude setup is the source of truth):')
      for (const f of changed) console.error(`  out of date: ${rel(f.path)}`)
      for (const o of orphans) console.error(`  orphaned:    ${rel(o)}`)
      console.error('Fix: make sync-opencode, then commit the result.')
      process.exit(1)
    }
    console.log('OpenCode parity: in sync.')
    return
  }
  const { changed, removed } = sync()
  if (!changed.length && !removed.length) console.log('OpenCode parity: already in sync.')
  for (const f of changed) console.log(`  wrote   ${f}`)
  for (const f of removed) console.log(`  removed ${f}`)
}

main()
